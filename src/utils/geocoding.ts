export const getCoordinates = (city?: string, lat?: number, lng?: number): [number, number] | null => {
  if (lat && lng) return [lat, lng];
  if (city && CITY_COORDINATES[city]) return CITY_COORDINATES[city];
  return null;
};

/**
 * Calculates the distance between two points in kilometers using the Haversine formula
 */
export const calculateDistance = (lat1: number, lon1: number, lat2: number, lon2: number): number => {
  const R = 6371; // Radius of the earth in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) * Math.cos(lat2 * (Math.PI / 180)) *
    Math.sin(dLon / 2) * Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const d = R * c; // Distance in km
  return d;
};

/**
 * Sorts members into distance bins based on their location relative to a home point.
 * Uses forEach to process the collection as requested.
 */
export const getMemberDistanceBins = (members: any[], homeLat: number, homeLng: number) => {
  const bins: Record<string, number> = {
    "0-10": 0,
    "11-25": 0,
    "26-50": 0,
    "51-100": 0,
    "100+": 0
  };

  members.forEach(member => {
    const coords = getCoordinates(member.city, member.lat, member.lng);
    if (!coords) return;

    const dist = calculateDistance(homeLat, homeLng, coords[0], coords[1]);
    
    let group = "";
    if (dist <= 10) group = "0-10";
    else if (dist <= 25) group = "11-25";
    else if (dist <= 50) group = "26-50";
    else if (dist <= 100) group = "51-100";
    else group = "100+";

    bins[group]++;
  });

  return bins;
};
